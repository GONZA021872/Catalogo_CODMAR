-- Add the configured category list to the public store configuration view.
-- This lets public category buttons match the administration menu, including empty categories.
create or replace view public.configuracion_tienda_codmar_publica as
 SELECT ci.nombre_comercial,
    ci.nombre_comercial_escritorio,
    ci.nombre_comercial_movil,
    ci.mostrar_nombre_comercial,
    ci.logotipo_url_escritorio,
    ci.logotipo_url_movil,
    ci.mostrar_logotipo,
    ci.color_franjas_escritorio,
    ci.color_franjas_movil,
    ci.fuente_nombre_comercial,
    ci.tamano_nombre_comercial,
    ci.tamano_nombre_comercial_escritorio,
    ci.tamano_nombre_comercial_movil,
    ci.ajuste_nombre_comercial_x_escritorio,
    ci.ajuste_nombre_comercial_y_escritorio,
    ci.ajuste_nombre_comercial_x_movil,
    ci.ajuste_nombre_comercial_y_movil,
    ci.ajuste_logotipo_x,
    ci.ajuste_logotipo_x_movil,
    ci.ajuste_logotipo_y_escritorio,
    ci.ajuste_logotipo_y_movil,
    ci.mostrar_buscador,
    ci.ajuste_buscador_x,
    ci.ajuste_buscador_y,
    ci.ancho_buscador,
    ci.alto_buscador,
    ci.ajuste_buscador_x_escritorio,
    ci.ajuste_buscador_y_escritorio,
    ci.ancho_buscador_escritorio,
    ci.alto_buscador_escritorio,
    ci.ajuste_buscador_x_movil,
    ci.ajuste_buscador_y_movil,
    ci.ancho_buscador_movil,
    ci.alto_buscador_movil,
    ci.mostrar_carrito,
    ci.tipo_carrito,
    ci.tipo_carrito_escritorio,
    ci.tipo_carrito_movil,
    ci.ajuste_carrito_x,
    ci.ajuste_carrito_y,
    ci.ajuste_carrito_x_escritorio,
    ci.ajuste_carrito_y_escritorio,
    ci.ajuste_carrito_x_movil,
    ci.ajuste_carrito_y_movil,
    ci.posicion_logotipo,
    ci.posicion_logotipo_escritorio,
    ci.posicion_logotipo_movil,
    ci.color_nombre_comercial,
    c.slug AS negocio_slug,
    ci.telefono_pedidos,
    ci.categorias
   FROM configuracion_inicio ci
     JOIN clientes c ON c.id = ci.cliente_id
  WHERE c.activo = true;

grant select on public.configuracion_tienda_codmar_publica to anon;
